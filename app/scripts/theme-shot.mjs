import { _electron as electron } from 'playwright-core';
import fs from 'node:fs';
const env={...process.env}; delete env.ELECTRON_RUN_AS_NODE; env.MATEPAD_QUIET='1';
fs.rmSync('/tmp/mp-light-profile',{recursive:true,force:true});
const app=await electron.launch({args:['.','--demo','--lang=en','--profile=/tmp/mp-light-profile'],cwd:process.cwd(),env});
const page=await app.firstWindow();
const errs=[]; page.on('pageerror',e=>errs.push(e.message)); page.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await page.waitForFunction(()=>window.__companionReady===true,null,{timeout:20000});
await page.waitForTimeout(500);
console.log('initial theme', await page.evaluate(()=>document.documentElement.dataset.theme));
await page.locator('[data-action="toggle-theme"]').click();
await page.waitForTimeout(700);
console.log('after toggle', await page.evaluate(()=>({theme:document.documentElement.dataset.theme,bg:getComputedStyle(document.body).backgroundColor})));
await page.screenshot({path:'screens/e2e/17-overview-light.png'});
await page.locator('.nav-item[data-nav="tools"]').click(); await page.waitForTimeout(400);
await page.screenshot({path:'screens/e2e/18-tools-light.png'});
await page.locator('.nav-item[data-nav="unlock"]').click(); await page.waitForTimeout(400);
await page.screenshot({path:'screens/e2e/19-unlock-light.png'});
await page.locator('#view [data-action="safety-checklist"]').click(); await page.waitForTimeout(250);
await page.screenshot({path:'screens/e2e/22-modal-light.png'});
await page.locator('#safety-close').click(); await page.waitForTimeout(200);
await page.locator('.nav-item[data-nav="settings"]').click(); await page.waitForTimeout(400);
await page.screenshot({path:'screens/e2e/20-settings-light.png'});
await page.locator('.nav-item[data-nav="console"]').click(); await page.waitForTimeout(400);
await page.screenshot({path:'screens/e2e/21-console-light.png'});
console.log('errors',JSON.stringify(errs));
await app.close();
if(errs.length) process.exit(1);
