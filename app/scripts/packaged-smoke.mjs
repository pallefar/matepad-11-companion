import { _electron as electron } from 'playwright-core';
import fs from 'node:fs';
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
env.MATEPAD_QUIET = '1';
const executablePath = '/tmp/mp-macpkg/MatePad 11 Companion-darwin-arm64/MatePad 11 Companion.app/Contents/MacOS/MatePad 11 Companion';
const profile = '/tmp/mp-packaged-profile';
fs.rmSync(profile, { recursive: true, force: true });
const app = await electron.launch({ executablePath, args: ['--demo', '--profile=' + profile, '--lang=en'], env });
const page = await app.firstWindow();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.waitForFunction(() => window.__companionReady === true, null, { timeout: 20000 });
console.log('title:', await page.title());
console.log('h1:', await page.locator('h1').first().innerText());
console.log('phases:', await page.locator('.phase').count());
await page.screenshot({ path: 'screens/packaged-asar.png' });
await page.locator('[data-action="toggle-theme"]').click();
await page.waitForTimeout(600);
const theme = await page.evaluate(() => ({ theme: document.documentElement.dataset.theme, bg: getComputedStyle(document.body).backgroundColor }));
console.log('light:', JSON.stringify(theme));
if (theme.theme !== 'light') errors.push('packaged theme toggle did not switch to light');
await page.screenshot({ path: 'screens/packaged-asar-light.png' });
await app.close();
console.log('errors:', JSON.stringify(errors));
if (errors.length) process.exit(1);
